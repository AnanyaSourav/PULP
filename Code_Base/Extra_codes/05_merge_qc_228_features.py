def save_removal_log(
    initial_features,
    missing_removed,
    variance_removed,
    correlation_removed
):

    rows = []

    for feature in initial_features:

        if feature in missing_removed:

            reason = "Missingness"

        elif feature in variance_removed:

            reason = "Zero_or_NearZero_Variance"

        elif feature in correlation_removed:

            reason = "High_Correlation"

        else:

            reason = "Retained"

        rows.append({
            "Feature": feature,
            "Status": (
                "Removed"
                if reason != "Retained"
                else "Retained"
            ),
            "Reason": reason
        })

    pd.DataFrame(rows).to_csv(
        REMOVAL_LOG_OUTPUT,
        sep="\t",
        index=False
    )

    print(
        f"Saved: {REMOVAL_LOG_OUTPUT}"
    )


