def merge_features(rdkit_df, three_d_df, rdkit_features):

    columns_3d = [ID_COLUMN] + THREE_D_FEATURES

    rdkit_part = rdkit_df[
        [ID_COLUMN] + rdkit_features
    ].copy()

    three_d_part = three_d_df[
        columns_3d
    ].copy()

    merged = pd.merge(
        rdkit_part,
        three_d_part,
        on=ID_COLUMN,
        how="inner",
        validate="one_to_one"
    )

    if len(merged) != len(rdkit_df):
        fail(
            "Merge changed row count.\n"
            f"Original: {len(rdkit_df):,}\n"
            f"Merged:   {len(merged):,}"
        )

    return merged


