def check_file(path):
    if not os.path.isfile(path):
        fail(f"Required file not found:\n{path}")


def load_tsv(path):
    print(f"Loading:\n{path}")
    try:
        df = pd.read_csv(
            path,
            sep="\t",
            low_memory=False
        )
    except Exception as e:
        fail(f"Could not read {path}\n{e}")

    print(f"Rows: {len(df):,}")
    print(f"Columns: {len(df.columns):,}")

    return df


def check_unique_ids(df, name):
    if ID_COLUMN not in df.columns:
        fail(f"{name}: missing {ID_COLUMN} column")

    duplicated = df[ID_COLUMN].duplicated().sum()

    print(f"{name} duplicate {ID_COLUMN}: {duplicated}")

    if duplicated > 0:
        fail(f"{name} contains duplicate {ID_COLUMN} values.")

    return duplicated


