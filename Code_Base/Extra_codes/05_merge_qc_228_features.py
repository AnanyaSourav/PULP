# NUMERIC CONVERSION
# ======================================================================

def force_numeric(df, features, dataset_name):

    conversion_failures = []

    for feature in features:

        original = df[feature]

        converted = pd.to_numeric(
            original,
            errors="coerce"
        )

        newly_missing = (
            original.notna()
            & converted.isna()
        ).sum()

        if newly_missing > 0:
            conversion_failures.append(
                (feature, int(newly_missing))
            )

        df[feature] = converted

    if conversion_failures:

        print(
            f"\n{dataset_name}: non-numeric values converted "
            "to NaN:"
        )

        for feature, count in conversion_failures:
            print(
                f"  {feature}: {count}"
            )

    return df


# ======================================================================
# TRAIN-ONLY MISSINGNESS QC
# ======================================================================

def missingness_qc(train, test, features):

    print_header("TRAIN-ONLY MISSINGNESS QC")

    missing_train = train[features].isna().sum()
    missing_test = test[features].isna().sum()

    train_missing_fraction = (
        missing_train / len(train)
    )

    remove = [
        feature
        for feature in features
        if train_missing_fraction[feature]
        > MISSINGNESS_THRESHOLD
    ]

    keep = [
        feature
        for feature in features
        if feature not in remove
    ]

    print(
        f"Missingness threshold: "
        f"{MISSINGNESS_THRESHOLD * 100:.1f}%"
    )

    print(
        f"Features removed by missingness: "
        f"{len(remove)}"
    )

    if remove:
        print("\nRemoved:")
        for feature in remove:
            print(
                f"  {feature}: "
                f"{train_missing_fraction[feature] * 100:.3f}%"
            )

    print(
        f"Features retained: {len(keep)}"
    )

    return keep, remove, missing_train, missing_test


# ======================================================================
# TRAIN-ONLY MEDIAN IMPUTATION
# ======================================================================

def median_imputation(train, test, features):

    print_header("TRAIN-ONLY MEDIAN IMPUTATION")

    train_medians = {}

    total_train_missing_before = (
        int(train[features].isna().sum().sum())
    )

    total_test_missing_before = (
        int(test[features].isna().sum().sum())
    )

    for feature in features:

        median = train[feature].median()

        if pd.isna(median):
            fail(
                f"Training median is NaN for feature: "
                f"{feature}"
            )

        train_medians[feature] = float(median)

        train[feature] = train[feature].fillna(median)
        test[feature] = test[feature].fillna(median)

    total_train_missing_after = (
        int(train[features].isna().sum().sum())
    )

    total_test_missing_after = (
        int(test[features].isna().sum().sum())
    )

    print(
        f"Training missing values before: "
        f"{total_train_missing_before:,}"
    )

    print(
        f"Testing missing values before : "
        f"{total_test_missing_before:,}"
    )

    print(
        f"Training missing values after : "
        f"{total_train_missing_after:,}"
    )

    print(
        f"Testing missing values after  : "
        f"{total_test_missing_after:,}"
    )

    if (
        total_train_missing_after > 0
        or total_test_missing_after > 0
    ):
        fail("Missing values remain after imputation.")

    return train_medians


# ======================================================================
# TRAIN-ONLY VARIANCE FILTER
# ======================================================================

def variance_filter(train, features):

    print_header("TRAIN-ONLY VARIANCE FILTER")

    variances = train[features].var(
        axis=0,
        ddof=0
    )

    remove = [
        feature
        for feature in features
        if (
            not np.isfinite(variances[feature])
            or variances[feature] <= VARIANCE_THRESHOLD
        )
    ]

    keep = [
        feature
        for feature in features
        if feature not in remove
    ]

    print(
        f"Variance threshold: {VARIANCE_THRESHOLD}"
    )

    print(
        f"Features removed: {len(remove)}"
    )

    if remove:
        print("\nRemoved:")
        for feature in remove:
            print(
                f"  {feature}: variance="
                f"{variances[feature]}"
            )

    print(
        f"Features retained: {len(keep)}"
    )

    return keep, remove, variances


# ======================================================================
# TRAIN-ONLY CORRELATION FILTER
# ======================================================================

def correlation_filter(train, features):

    print_header("TRAIN-ONLY CORRELATION FILTER")

    if len(features) <= 1:
        return features, [], {}

    print(
        f"Calculating correlation matrix for "
        f"{len(features)} features..."
    )

    corr = train[features].corr(
        method="pearson"
    )

    upper = corr.where(
        np.triu(
            np.ones(corr.shape),
            k=1
        ).astype(bool)
    )

    remove = set()
    correlation_pairs = []

    for column in upper.columns:

        correlated = upper.index[
            upper[column].abs()
            > CORRELATION_THRESHOLD
        ].tolist()

        for row in correlated:

            if row not in remove:

                remove.add(column)

                correlation_pairs.append(
                    (
                        row,
                        column,
                        float(corr.loc[row, column])
                    )
                )

                break

    remove = list(remove)

    keep = [
        feature
        for feature in features
        if feature not in remove
    ]

    print(
        f"Correlation threshold: "
        f"{CORRELATION_THRESHOLD}"
    )

    print(
        f"Features removed: {len(remove)}"
    )

    if correlation_pairs:

        print("\nHighly correlated pairs:")

        for a, b, r in correlation_pairs[:30]:

            print(
                f"  {a} <-> {b}: "
                f"r={r:.5f}"
            )

        if len(correlation_pairs) > 30:

            print(
                f"  ... and "
                f"{len(correlation_pairs) - 30} "
                f"additional pairs"
            )

    print(
        f"Features retained: {len(keep)}"
    )

    return keep, remove, correlation_pairs


# ======================================================================
# DUPLICATE FEATURE COLUMN CHECK
# ======================================================================

def duplicate_feature_columns(df, features):

    duplicates = []

    seen = {}

    for feature in features:

        values = pd.util.hash_pandas_object(
            df[feature],
            index=False
        ).values.tobytes()

        if values in seen:

            duplicates.append(
                (feature, seen[values])
            )

        else:

            seen[values] = feature

    return duplicates


