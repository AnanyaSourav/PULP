def final_numeric_qc(train, test, features):

    print_header("FINAL NUMERICAL QC")

    train_nan = int(
        train[features].isna().sum().sum()
    )

    test_nan = int(
        test[features].isna().sum().sum()
    )

    train_inf = int(
        np.isinf(
            train[features].to_numpy()
        ).sum()
    )

    test_inf = int(
        np.isinf(
            test[features].to_numpy()
        ).sum()
    )

    print(f"Training NaN: {train_nan}")
    print(f"Testing NaN : {test_nan}")

    print(f"Training Inf: {train_inf}")
    print(f"Testing Inf : {test_inf}")

    if train_nan or test_nan:
        fail("NaN values remain in final features.")

    if train_inf or test_inf:
        fail("Inf values remain in final features.")

    print("Final numerical QC: PASS")


# ======================================================================
# SAVE PREPROCESSING STATISTICS
# ======================================================================

def save_preprocessing_statistics(
    train,
    features,
    medians,
    variance_values
):

    rows = []

    for feature in features:

        series = train[feature]

        rows.append({
            "Feature": feature,
            "Train_Median": medians.get(
                feature,
                np.nan
            ),
            "Train_Mean": float(
                series.mean()
            ),
            "Train_Std": float(
                series.std(ddof=0)
            ),
            "Train_Min": float(
                series.min()
            ),
            "Train_Max": float(
                series.max()
            ),
            "Train_Variance": float(
                variance_values.get(
                    feature,
                    series.var(ddof=0)
                )
            )
        })

    stats = pd.DataFrame(rows)

    stats.to_csv(
        PREPROCESSING_OUTPUT,
        sep="\t",
        index=False
    )

    print(
        f"Saved: {PREPROCESSING_OUTPUT}"
    )


