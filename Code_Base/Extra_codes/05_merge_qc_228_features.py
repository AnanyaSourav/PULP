    check_row_count(
        rdkit_test,
        expected_test,
        "RDKit TEST"
    )

    check_row_count(
        three_d_train,
        expected_train,
        "3D TRAIN"
    )

    check_row_count(
        three_d_test,
        expected_test,
        "3D TEST"
    )

    # --------------------------------------------------------------
    # DUPLICATE IDS
    # --------------------------------------------------------------

    print_header("ID VALIDATION")

    check_unique_ids(
        rdkit_train,
        "RDKit TRAIN"
    )

    check_unique_ids(
        rdkit_test,
        "RDKit TEST"
    )

    check_unique_ids(
        three_d_train,
        "3D TRAIN"
    )

    check_unique_ids(
        three_d_test,
        "3D TEST"
    )

    # --------------------------------------------------------------
    # TRAIN TEST LEAKAGE
    # --------------------------------------------------------------

    print_header("TRAIN / TEST LEAKAGE CHECK")

    check_train_test_overlap(
        rdkit_train,
        rdkit_test
    )

    # --------------------------------------------------------------
    # DESCRIPTOR LIST
    # --------------------------------------------------------------

    print_header("LOADING AUTHORITATIVE RDKit DESCRIPTOR LIST")

    descriptor_list = read_descriptor_list(
        DESCRIPTOR_LIST
    )

    print(
        f"RDKit descriptor list: "
        f"{len(descriptor_list)}"
    )

    # --------------------------------------------------------------
    # VALIDATE RDKit
    # --------------------------------------------------------------

    rdkit_features = validate_rdkit_descriptors(
        rdkit_train,
        rdkit_test,
        descriptor_list
    )

    # --------------------------------------------------------------
    # VALIDATE 3D
    # --------------------------------------------------------------

    three_d_features = validate_3d_descriptors(
        three_d_train,
        three_d_test
    )

    # --------------------------------------------------------------
    # ID MATCHING
    # --------------------------------------------------------------

    check_id_matching(
        rdkit_train,
        three_d_train,
        rdkit_test,
        three_d_test
    )

    # --------------------------------------------------------------
    # INITIAL FEATURE LIST
    # --------------------------------------------------------------

    initial_features = (
        rdkit_features
        + three_d_features
    )

    print_header("INITIAL FEATURE COMPOSITION")

    print(
        f"RDKit features: {len(rdkit_features)}"
    )

    print(
        f"3D features:    {len(three_d_features)}"
    )

    print(
        f"TOTAL features: {len(initial_features)}"
    )

    if len(initial_features) != EXPECTED_TOTAL:

        fail(
            f"Expected {EXPECTED_TOTAL} total features "
            f"but found {len(initial_features)}."
        )

    # --------------------------------------------------------------
    # MERGE
    # --------------------------------------------------------------

    print_header("MERGING RDKit + 3D FEATURES")

    train = merge_features(
        rdkit_train,
        three_d_train,
        rdkit_features
    )

    test = merge_features(
        rdkit_test,
        three_d_test,
        rdkit_features
    )

    print(
        f"Merged TRAIN rows: {len(train):,}"
    )

    print(
        f"Merged TEST rows : {len(test):,}"
    )

    # --------------------------------------------------------------
    # TARGET VALIDATION
    # --------------------------------------------------------------

    print_header("TARGET VALIDATION")

    if TARGET_COLUMN not in rdkit_train.columns:

        fail(
            f"Target column missing: {TARGET_COLUMN}"
        )

    train_target = (
        rdkit_train[
            [ID_COLUMN, TARGET_COLUMN]
        ]
        .copy()
    )

    test_target = (
        rdkit_test[
            [ID_COLUMN, TARGET_COLUMN]
        ]
        .copy()
    )

    train = train.merge(
        train_target,
        on=ID_COLUMN,
        how="left",
        validate="one_to_one",
        suffixes=("", "_target")
    )

    test = test.merge(
        test_target,
        on=ID_COLUMN,
        how="left",
        validate="one_to_one",
        suffixes=("", "_target")
    )

    if TARGET_COLUMN + "_target" in train.columns:

        if not (
            train[TARGET_COLUMN]
            == train[TARGET_COLUMN + "_target"]
        ).all():

            fail(
                "TRAIN target mismatch detected."
            )

        train.drop(
            columns=[TARGET_COLUMN + "_target"],
            inplace=True
        )

    if TARGET_COLUMN + "_target" in test.columns:

        if not (
            test[TARGET_COLUMN]
            == test[TARGET_COLUMN + "_target"]
        ).all():

            fail(
                "TEST target mismatch detected."
            )

        test.drop(
            columns=[TARGET_COLUMN + "_target"],
            inplace=True
        )

    print(
        "Target validation: PASS"
    )

    print(
        "\nTraining target distribution:"
    )

    print(
        train[TARGET_COLUMN].value_counts(
            dropna=False
        ).sort_index()
    )

    print(
        "\nTesting target distribution:"
    )

    print(
        test[TARGET_COLUMN].value_counts(
            dropna=False
        ).sort_index()
    )

    # --------------------------------------------------------------
    # NUMERIC CONVERSION
    # --------------------------------------------------------------

    print_header("NUMERIC FEATURE CONVERSION")

    train = force_numeric(
        train,
        initial_features,
        "TRAIN"
    )

    test = force_numeric(
        test,
        initial_features,
        "TEST"
    )

    # --------------------------------------------------------------
    # MISSINGNESS
    # --------------------------------------------------------------

    (
        features_after_missing,
        missing_removed,
        missing_train,
        missing_test
    ) = missingness_qc(
        train,
        test,
        initial_features
    )

    # --------------------------------------------------------------
    # MEDIAN IMPUTATION
    # --------------------------------------------------------------

    train_medians = median_imputation(
        train,
        test,
        features_after_missing
    )

    # --------------------------------------------------------------
    # VARIANCE
    # --------------------------------------------------------------

    (
        features_after_variance,
        variance_removed,
        variance_values
    ) = variance_filter(
        train,
        features_after_missing
    )

    # --------------------------------------------------------------
    # CORRELATION
    # --------------------------------------------------------------

    (
        final_features,
        correlation_removed,
        correlation_pairs
    ) = correlation_filter(
        train,
        features_after_variance
    )

    # --------------------------------------------------------------
    # FINAL FEATURE COUNT
    # --------------------------------------------------------------

    print_header("FINAL FEATURE SELECTION")

    print(
        f"Initial features: "
        f"{len(initial_features)}"
    )

    print(
        f"Removed by missingness: "
        f"{len(missing_removed)}"
    )

    print(
        f"Removed by variance: "
        f"{len(variance_removed)}"
    )

    print(
        f"Removed by correlation: "
        f"{len(correlation_removed)}"
    )

    print(
        f"FINAL FEATURES: "
        f"{len(final_features)}"
    )

    # --------------------------------------------------------------
    # CHECK DUPLICATE FEATURE COLUMNS
    # --------------------------------------------------------------

    print_header("DUPLICATE FEATURE COLUMN CHECK")

    duplicates_train = duplicate_feature_columns(
        train,
        final_features
    )

    duplicates_test = duplicate_feature_columns(
        test,
        final_features
    )

    print(
        f"Training duplicate feature columns: "
        f"{len(duplicates_train)}"
    )

    print(
        f"Testing duplicate feature columns: "
        f"{len(duplicates_test)}"
    )

    if duplicates_train:

        print(
            "WARNING: duplicate feature columns "
            "detected in TRAIN."
        )

    if duplicates_test:

        print(
            "WARNING: duplicate feature columns "
            "detected in TEST."
        )

    # --------------------------------------------------------------
    # FINAL NUMERIC QC
    # --------------------------------------------------------------

    final_numeric_qc(
        train,
        test,
        final_features
    )

    # --------------------------------------------------------------
    # BUILD FINAL DATASETS
    # --------------------------------------------------------------

    print_header("BUILDING FINAL DATASETS")

    # Keep useful identifiers and target.
    output_columns = [
        ID_COLUMN,
        TARGET_COLUMN
    ] + final_features

    # Remove possible duplicate columns.
    output_columns = list(
        dict.fromkeys(output_columns)
    )

    final_train = train[
        output_columns
    ].copy()

    final_test = test[
        output_columns
    ].copy()

    # --------------------------------------------------------------
    # CHECK FEATURE ORDER
    # --------------------------------------------------------------

    train_feature_columns = [
        c for c in final_train.columns
        if c not in [ID_COLUMN, TARGET_COLUMN]
    ]

    test_feature_columns = [
        c for c in final_test.columns
        if c not in [ID_COLUMN, TARGET_COLUMN]
    ]

    if train_feature_columns != test_feature_columns:

        fail(
            "TRAIN/TEST feature ordering mismatch."
        )

    print(
        "TRAIN/TEST feature ordering: PASS"
    )

    # --------------------------------------------------------------
    # FINAL SHAPES
    # --------------------------------------------------------------

    print(
        f"Training final shape: "
        f"{final_train.shape}"
    )

    print(
        f"Testing final shape : "
        f"{final_test.shape}"
    )

    # --------------------------------------------------------------
    # SAVE
    # --------------------------------------------------------------

    print_header("SAVING FINAL DATASETS")

    final_train.to_csv(
        TRAIN_OUTPUT,
        sep="\t",
        index=False
    )

    final_test.to_csv(
        TEST_OUTPUT,
        sep="\t",
        index=False
    )

    print(
        f"Saved: {TRAIN_OUTPUT}"
    )

    print(
        f"Saved: {TEST_OUTPUT}"
    )

    # --------------------------------------------------------------
    # SAVE METADATA
    # --------------------------------------------------------------

    save_feature_list(
        final_features
    )

    save_removed_features(
        missing_removed,
        variance_removed,
        correlation_removed
    )

    save_removal_log(
        initial_features,
        missing_removed,
        variance_removed,
        correlation_removed
    )

    save_preprocessing_statistics(
        train,
        final_features,
        train_medians,
        variance_values
    )

    save_qc_summary(
        initial_features,
        missing_removed,
        variance_removed,
        correlation_removed,
        final_features,
        final_train,
        final_test
    )

    # --------------------------------------------------------------
    # FINAL SUMMARY
    # --------------------------------------------------------------

    runtime = (
        time.time()
        - start_time
    )

    print_header("SCRIPT 05 v3 — FINAL SUMMARY")

    print(
        f"RDKit descriptors: "
        f"{EXPECTED_RDKIT}"
    )

    print(
        f"3D descriptors:    "
        f"{EXPECTED_3D}"
    )

    print(
        f"Initial features:  "
        f"{EXPECTED_TOTAL}"
    )

    print(
        f"Final features:    "
        f"{len(final_features)}"
    )

    print(
        f"Training molecules: "
        f"{len(final_train):,}"
    )

    print(
        f"Testing molecules:  "
        f"{len(final_test):,}"
    )

    print(
        f"Training NaN: "
        f"{int(final_train[final_features].isna().sum().sum())}"
    )

    print(
        f"Testing NaN:  "
        f"{int(final_test[final_features].isna().sum().sum())}"
    )

    print(
        f"Training Inf: "
        f"{int(np.isinf(final_train[final_features].to_numpy()).sum())}"
    )

    print(
        f"Testing Inf:  "
        f"{int(np.isinf(final_test[final_features].to_numpy()).sum())}"
    )

    print()
    print(
        "FINAL QC: PASS"
    )

    print()
    print(
        f"Runtime: {runtime / 60:.2f} minutes"
    )

    print()
    print(
        "OUTPUT FILES:"
    )

    print(
        TRAIN_OUTPUT
    )

    print(
        TEST_OUTPUT
    )

    print(
        FEATURE_LIST_OUTPUT
    )

    print(
        REMOVED_FEATURE_OUTPUT
    )

    print(
        PREPROCESSING_OUTPUT
    )

    print(
        QC_SUMMARY_OUTPUT
    )

    print(
        REMOVAL_LOG_OUTPUT
    )

    print()
    print("=" * 78)
    print("SCRIPT 05 v3 COMPLETED SUCCESSFULLY")
    print("=" * 78)


