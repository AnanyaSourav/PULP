def figure_09_validation_summary(
    validation_df: Optional[pd.DataFrame],
) -> None:

    stem = "09_validation_summary"

    if validation_df is None or validation_df.empty:
        skip_figure(
            stem,
            "06_validation_summary.tsv unavailable",
        )
        return

    numeric_cols = find_numeric_columns(
        validation_df
    )

    if not numeric_cols:
        skip_figure(
            stem,
            "validation summary contains no numeric metrics",
        )
        return

    # Identify a metric/name column.
    metric_col = find_column(
        validation_df,
        exact=[
            "Metric",
            "Measure",
            "Statistic",
            "Validation_Metric",
            "Summary_Metric",
        ],
    )

    value_col = None

    if metric_col is not None:

        candidates = [
            c
            for c in numeric_cols
            if c != metric_col
        ]

        if len(candidates) == 1:
            value_col = candidates[0]

    # If there is no obvious long-format structure, skip rather
    # than generating an arbitrary plot.
    if metric_col is None or value_col is None:

        skip_figure(
            stem,
            "validation summary is not in a supported metric/value format",
        )
        return

    plot_df = validation_df[
        [metric_col, value_col]
    ].copy()

    plot_df[value_col] = clean_numeric(
        plot_df[value_col]
    )

    plot_df = plot_df.dropna()

    if plot_df.empty:
        skip_figure(
            stem,
            "no numeric metric/value observations",
        )
        return

    plot_df = plot_df.head(
        min(MAX_LABELS, len(plot_df))
    )

    fig_height = max(
        FIGURE_HEIGHT,
        0.35 * len(plot_df),
    )

    fig, ax = plt.subplots(
        figsize=(FIGURE_WIDTH, fig_height)
    )

    y = np.arange(len(plot_df))

    ax.barh(
        y,
        plot_df[value_col],
    )

    ax.set_yticks(y)

    ax.set_yticklabels(
        plot_df[metric_col].astype(str)
    )

    ax.invert_yaxis()

    ax.set_xlabel(str(value_col))
    ax.set_title(
        "Target/off-target validation summary"
    )

    ax.grid(
        axis="x",
        alpha=0.25,
    )

    save_figure(fig, stem)


