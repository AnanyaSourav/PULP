def figure_06_similarity_distribution(
    target_df: Optional[pd.DataFrame],
) -> None:

    stem = "06_similarity_distribution"

    if target_df is None or target_df.empty:
        skip_figure(stem, "target recovery table unavailable")
        return

    similarity_col = find_similarity_column(target_df)

    if similarity_col is None:
        skip_figure(stem, "similarity column unavailable")
        return

    similarity = clean_numeric(
        target_df[similarity_col]
    )

    valid = similarity.notna()

    if valid.sum() < 10:
        skip_figure(
            stem,
            "fewer than 10 valid similarity observations",
        )
        return

    recovery = derive_recovery_boolean(target_df)

    if recovery is None:
        skip_figure(
            stem,
            "recovery indicator unavailable",
        )
        return

    plot_df = pd.DataFrame(
        {
            "Similarity": similarity,
            "Recovered": recovery,
        }
    ).dropna()

    if plot_df.empty:
        skip_figure(
            stem,
            "no complete similarity/recovery observations",
        )
        return

    recovered = plot_df.loc[
        plot_df["Recovered"].astype(bool),
        "Similarity",
    ]

    not_recovered = plot_df.loc[
        ~plot_df["Recovered"].astype(bool),
        "Similarity",
    ]

    if len(recovered) < 2 or len(not_recovered) < 2:
        skip_figure(
            stem,
            "both recovered and non-recovered groups require at least two observations",
        )
        return

    fig, ax = plt.subplots(
        figsize=(FIGURE_WIDTH, FIGURE_HEIGHT)
    )

    ax.hist(
        recovered,
        bins=30,
        alpha=0.60,
        density=True,
        label="Recovered",
    )

