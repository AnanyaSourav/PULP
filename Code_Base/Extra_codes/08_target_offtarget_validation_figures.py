    ax.set_xticks(result["Top_K"])

    ax.set_ylim(
        max(0, result["Recovery"].min() - 0.05),
        min(1, result["Recovery"].max() + 0.05),
    )

    ax.grid(
        axis="both",
        alpha=0.25,
    )

    save_figure(fig, stem)


