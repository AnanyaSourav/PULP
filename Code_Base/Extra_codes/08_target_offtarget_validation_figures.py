def figure_01_similarity_threshold_recovery(
    threshold_df: Optional[pd.DataFrame],
) -> None:

    stem = "01_similarity_threshold_recovery"

    if threshold_df is None or threshold_df.empty:
        skip_figure(stem, "06_similarity_threshold_summary.tsv unavailable")
        return

    threshold_col = find_column(
        threshold_df,
        exact=[
            "Similarity_Threshold",
            "Threshold",
            "Cosine_Threshold",
            "SimilarityThreshold",
        ],
    )

    if threshold_col is None:

        # Search numeric columns whose name contains threshold.
        for c in threshold_df.columns:
            if "threshold" in norm(c) and is_numeric_series(threshold_df[c]):
                threshold_col = c
                break

    if threshold_col is None:
        skip_figure(stem, "similarity-threshold column unavailable")
        return

    threshold = clean_numeric(threshold_df[threshold_col])

    metric_columns = []

    for c in threshold_df.columns:

        if c == threshold_col:
            continue

        if not is_numeric_series(threshold_df[c]):
            continue

        n = norm(c)

        if any(
            token in n
            for token in [
                "recall",
                "recovery",
                "precision",
                "coverage",
                "hit_rate",
                "sensitivity",
                "candidate",
                "retrieval",
            ]
        ):
            metric_columns.append(c)

    if not metric_columns:

        skip_figure(
            stem,
            "no supported numeric recovery/coverage metrics found",
        )
        return

    plot_df = threshold_df[[threshold_col] + metric_columns].copy()
    plot_df[threshold_col] = threshold

    plot_df = plot_df.dropna(subset=[threshold_col])
    plot_df = plot_df.sort_values(threshold_col)

    if plot_df.empty:
        skip_figure(stem, "no valid threshold observations")
        return

    fig, ax = plt.subplots(
        figsize=(FIGURE_WIDTH, FIGURE_HEIGHT)
    )

    plotted = 0

    for col in metric_columns:

        y = clean_numeric(plot_df[col])

        valid = y.notna()

        if valid.sum() < 2:
            continue

        ax.plot(
            plot_df.loc[valid, threshold_col],
            y.loc[valid],
            marker="o",
            linewidth=2,
            label=str(col),
        )

        plotted += 1

    if plotted == 0:

        plt.close(fig)

        skip_figure(
            stem,
            "no metric contained at least two numeric observations",
        )
        return

    ax.set_xlabel("40D cosine similarity threshold")
    ax.set_ylabel("Validation metric")
    ax.set_title(
        "Target/off-target recovery across similarity thresholds"
    )

    ax.grid(
        axis="both",
        alpha=0.25,
        linewidth=0.8,
    )

    ax.legend(
        frameon=False,
        loc="best",
    )

    save_figure(fig, stem)


