def calculate_top_k_recovery(
    df: pd.DataFrame,
    rank_col: str,
    recovery: pd.Series,
) -> Optional[pd.DataFrame]:

    ranks = clean_numeric(df[rank_col])

    working = pd.DataFrame(
        {
            "rank": ranks,
            "recovered": recovery,
        }
    )

    working = working.dropna(subset=["rank", "recovered"])

    if working.empty:
        return None

    rows = []

    for k in TOP_K_VALUES:

        subset = working[working["rank"] <= k]

        if subset.empty:
            continue

        rows.append(
            {
                "Top_K": k,
                "Recovery": subset["recovered"].astype(bool).mean(),
                "N": len(subset),
            }
        )

    if not rows:
        return None

    return pd.DataFrame(rows)


