# =============================================================================

def write_derived_metrics(
    target_df: Optional[pd.DataFrame],
    neighbor_df: Optional[pd.DataFrame],
    off_df: Optional[pd.DataFrame],
) -> None:

    rows = []

    datasets = [
        ("target_recovery", target_df),
        ("neighbor_recovery", neighbor_df),
        ("offtarget_recovery", off_df),
    ]

    for name, df in datasets:

        if df is None or df.empty:
            continue

        rank_col = find_rank_column(df)

        recovery = derive_recovery_boolean(df)

        similarity_col = find_similarity_column(df)

        row = {
            "Dataset": name,
            "Rows": len(df),
            "Rank_Column": rank_col or "",
            "Similarity_Column": similarity_col or "",
            "Recovery_Column": (
                find_recovery_column(df) or ""
            ),
        }

        if recovery is not None:

            valid = recovery.notna()

            row["Recovery_Observations"] = int(
                valid.sum()
            )

            if valid.sum() > 0:
                row["Recovery_Fraction"] = float(
                    recovery.loc[valid].astype(bool).mean()
                )

        if rank_col is not None:

            rank = clean_numeric(
                df[rank_col]
            ).dropna()

            if not rank.empty:
                row["Median_Rank"] = float(
                    rank.median()
                )

                row["Mean_Rank"] = float(
                    rank.mean()
                )

        if similarity_col is not None:

            similarity = clean_numeric(
                df[similarity_col]
            ).dropna()

            if not similarity.empty:

                row["Mean_Similarity"] = float(
                    similarity.mean()
                )

                row["Median_Similarity"] = float(
                    similarity.median()
                )

        rows.append(row)

    if not rows:
        log(
            "No derived validation metrics could be calculated."
        )
        return

    output = OUTPUT_DIR / "08_derived_validation_metrics.tsv"

    pd.DataFrame(rows).to_csv(
        output,
        sep="\t",
        index=False,
    )

    log(
        f"WRITTEN | {output}"
    )


