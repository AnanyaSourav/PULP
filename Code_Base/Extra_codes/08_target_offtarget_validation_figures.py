# FIGURE 08 — CANDIDATE BURDEN VS THRESHOLD
# =============================================================================

def figure_08_candidate_burden(
    threshold_df: Optional[pd.DataFrame],
) -> None:

    stem = "08_candidate_burden_vs_threshold"

    if threshold_df is None or threshold_df.empty:
        skip_figure(
            stem,
            "06_similarity_threshold_summary.tsv unavailable",
        )
        return

    threshold_col = find_column(
        threshold_df,
        exact=[
            "Similarity_Threshold",
            "Threshold",
            "Cosine_Threshold",
        ],
    )

    if threshold_col is None:
        skip_figure(
            stem,
            "threshold column unavailable",
        )
        return

    candidate_col = None

    for c in threshold_df.columns:

        n = norm(c)

        if (
            "candidate" in n
            and is_numeric_series(threshold_df[c])
        ):
            candidate_col = c
            break

        if (
            "retrieved" in n
            and "count" in n
            and is_numeric_series(threshold_df[c])
        ):
            candidate_col = c
            break

    if candidate_col is None:
        skip_figure(
            stem,
            "candidate-count metric unavailable",
        )
        return

    x = clean_numeric(
        threshold_df[threshold_col]
    )

    y = clean_numeric(
        threshold_df[candidate_col]
    )

    valid = x.notna() & y.notna()

    if valid.sum() < 2:
        skip_figure(
            stem,
            "fewer than two valid threshold/candidate observations",
        )
        return

    fig, ax = plt.subplots(
        figsize=(FIGURE_WIDTH, FIGURE_HEIGHT)
    )

    ax.plot(
        x.loc[valid],
        y.loc[valid],
        marker="o",
        linewidth=2.5,
    )

    ax.set_xlabel("40D cosine similarity threshold")
    ax.set_ylabel("Candidate count")
    ax.set_title(
        "Candidate burden across similarity thresholds"
    )

    ax.grid(
        axis="both",
        alpha=0.25,
    )

    save_figure(fig, stem)


