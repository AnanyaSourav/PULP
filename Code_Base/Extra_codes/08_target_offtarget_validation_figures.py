# FIGURE 05 — RANKING PERFORMANCE
# =============================================================================

def figure_05_target_ranking_performance(
    target_df: Optional[pd.DataFrame],
) -> None:

    stem = "05_target_ranking_performance"

    if target_df is None or target_df.empty:
        skip_figure(stem, "target recovery table unavailable")
        return

    rank_col = find_rank_column(target_df)

    if rank_col is None:
        skip_figure(stem, "target rank column unavailable")
        return

    ranks = clean_numeric(target_df[rank_col]).dropna()

    if ranks.empty:
        skip_figure(stem, "no valid target ranks")
        return

    ranks = ranks[ranks > 0]

    if ranks.empty:
        skip_figure(stem, "target ranks contain no positive values")
        return

    # Calculate cumulative fraction recovered by rank.
    max_rank = int(min(50, ranks.max()))

    rank_values = np.arange(
        1,
        max_rank + 1,
    )

    recovery = [
        float((ranks <= k).mean())
        for k in rank_values
    ]

    fig, ax = plt.subplots(
        figsize=(FIGURE_WIDTH, FIGURE_HEIGHT)
    )

    ax.plot(
        rank_values,
        recovery,
        linewidth=2.5,
    )

    ax.scatter(
        TOP_K_VALUES,
        [
            recovery[k - 1]
            if k <= len(recovery)
            else np.nan
            for k in TOP_K_VALUES
        ],
        s=45,
    )

    ax.set_xlabel("Target rank")
    ax.set_ylabel("Cumulative fraction")
    ax.set_title(
        "Cumulative target-ranking performance"
    )

    ax.set_xlim(
        1,
        max_rank,
    )

    ax.set_ylim(
        0,
        min(1, max(recovery) + 0.05),
    )

    ax.grid(
        axis="both",
        alpha=0.25,
    )

    save_figure(fig, stem)


