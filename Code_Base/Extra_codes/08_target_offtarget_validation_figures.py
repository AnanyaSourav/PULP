def find_hierarchy_columns(df: pd.DataFrame) -> list[str]:

    hierarchy = []

    preferred = [
        "Class_1",
        "Class_Level1",
        "Class_Level_1",
        "Class_2",
        "Class_Level2",
        "Class_Level_2",
        "Class_3",
        "Class_Level3",
        "Class_Level_3",
        "Protein",
        "Protein_Name",
        "Gene",
        "Gene_Symbol",
    ]

    for wanted in preferred:

        col = find_column(
            df,
            exact=[wanted],
        )

        if col is not None and col not in hierarchy:
            hierarchy.append(col)

    return hierarchy


def figure_07_target_hierarchy_recovery(
    target_df: Optional[pd.DataFrame],
) -> None:

    stem = "07_target_hierarchy_recovery"

    if target_df is None or target_df.empty:
        skip_figure(stem, "target recovery table unavailable")
        return

    recovery = derive_recovery_boolean(target_df)

    if recovery is None:
        skip_figure(
            stem,
            "target recovery indicator unavailable",
        )
        return

    hierarchy_cols = find_hierarchy_columns(target_df)

    if not hierarchy_cols:
        skip_figure(
            stem,
            "target hierarchy columns unavailable",
        )
        return

    values = []

    recovered_mask = recovery.astype(bool)

    for col in hierarchy_cols:

        total = target_df[col].notna().sum()

        if total == 0:
            continue

        recovered = (
            target_df.loc[
                recovered_mask,
                col,
            ].notna().sum()
        )

        values.append(
            {
                "Level": str(col),
                "Recovery": recovered / total,
                "N": int(total),
            }
        )

    if len(values) < 2:
        skip_figure(
            stem,
            "insufficient hierarchy levels for comparison",
        )
        return

    result = pd.DataFrame(values)

    fig, ax = plt.subplots(
        figsize=(FIGURE_WIDTH, FIGURE_HEIGHT)
    )

    ax.bar(
        result["Level"],
        result["Recovery"],
    )

    ax.set_xlabel("Target annotation level")
    ax.set_ylabel("Recovered fraction")
    ax.set_title(
        "Recovery across target annotation hierarchy"
    )

    ax.set_ylim(
        0,
        min(
            1,
            result["Recovery"].max() + 0.10,
        ),
    )

    ax.tick_params(
        axis="x",
        rotation=35,
    )

    ax.grid(
        axis="y",
        alpha=0.25,
    )

    save_figure(fig, stem)


