def save_figure(fig: plt.Figure, stem: str) -> None:

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    paths = []

    for extension in ["png", "pdf", "svg"]:

        output = OUTPUT_DIR / f"{stem}.{extension}"

        if extension == "png":
            fig.savefig(
                output,
                dpi=FIGURE_DPI,
                bbox_inches="tight",
            )
        else:
            fig.savefig(
                output,
                bbox_inches="tight",
            )

        paths.append(str(output))

    plt.close(fig)

    GENERATED.append(
        {
            "figure": stem,
            "files": paths,
        }
    )

    log(
        f"GENERATED | {stem} | "
        f"PNG + PDF + SVG"
    )


