def write_schema_report(
    tables: dict[str, Optional[pd.DataFrame]]
) -> None:

    report_path = OUTPUT_DIR / "08_validation_schema_report.tsv"

    rows = []

    for name, df in tables.items():

        if df is None:
            rows.append(
                {
                    "Table": name,
                    "Rows": np.nan,
                    "Columns": np.nan,
                    "Column_Name": "",
                    "Detected_Type": "MISSING",
                }
            )
            continue

        for col in df.columns:

            dtype = str(df[col].dtype)

            rows.append(
                {
                    "Table": name,
                    "Rows": len(df),
                    "Columns": len(df.columns),
                    "Column_Name": str(col),
                    "Detected_Type": dtype,
                }
            )

    pd.DataFrame(rows).to_csv(
        report_path,
        sep="\t",
        index=False,
    )

    log(
        f"WRITTEN | {report_path}"
    )


