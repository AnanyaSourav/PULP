def norm(text) -> str:
    """
    Normalize a column name for matching.
    """
    text = str(text).strip().lower()
    text = re.sub(r"[^a-z0-9]+", "_", text)
    return text.strip("_")


def clean_numeric(series: pd.Series) -> pd.Series:
    """
    Convert a Series to numeric without inventing values.
    """
    return pd.to_numeric(series, errors="coerce")


def is_numeric_series(series: pd.Series, minimum_fraction: float = 0.70) -> bool:
    """
    Check whether enough values can be interpreted numerically.
    """
    if series.empty:
        return False

    numeric = pd.to_numeric(series, errors="coerce")
    return numeric.notna().mean() >= minimum_fraction


def find_column(
    df: pd.DataFrame,
    exact: Iterable[str] = (),
    contains_all: Iterable[str] = (),
    contains_any: Iterable[str] = (),
    exclude: Iterable[str] = (),
) -> Optional[str]:

    normalized = {c: norm(c) for c in df.columns}

    exact_norm = {norm(x) for x in exact}
    contains_all_norm = [norm(x) for x in contains_all]
    contains_any_norm = [norm(x) for x in contains_any]
    exclude_norm = [norm(x) for x in exclude]

    # Exact match first.
    for col, ncol in normalized.items():
        if ncol in exact_norm:
            return col

    # All tokens.
    if contains_all_norm:
        for col, ncol in normalized.items():
            if all(token in ncol for token in contains_all_norm):
                if not any(token in ncol for token in exclude_norm):
                    return col

    # Any token.
    if contains_any_norm:
        for col, ncol in normalized.items():
            if any(token in ncol for token in contains_any_norm):
                if not any(token in ncol for token in exclude_norm):
                    return col

    return None


def find_numeric_columns(df: pd.DataFrame) -> list[str]:
    return [
        c
        for c in df.columns
        if is_numeric_series(df[c])
    ]


def read_tsv(path: Path) -> Optional[pd.DataFrame]:

    if not path.exists():
        SKIPPED.append(f"MISSING FILE: {path}")
        log(f"WARNING | Missing: {path}")
        return None

    try:
        df = pd.read_csv(path, sep="\t", low_memory=False)

        log(
            f"LOADED | {path.name} | "
            f"rows={len(df):,} | cols={len(df.columns)}"
        )

        log(
            "         columns = "
            + ", ".join(str(c) for c in df.columns)
        )

        return df

    except Exception as exc:
        ERRORS.append(f"{path}: {exc}")
        log(f"ERROR | Failed reading {path}: {exc}")
        return None


