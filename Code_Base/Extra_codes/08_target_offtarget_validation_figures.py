def to_boolean(series: pd.Series) -> pd.Series:

    def convert(value):

        if pd.isna(value):
            return np.nan

        if isinstance(value, (bool, np.bool_)):
            return bool(value)

        if isinstance(value, (int, float, np.integer, np.floating)):
            if value == 1:
                return True
            if value == 0:
                return False

        value_norm = norm(value)

        if value_norm in TRUE_VALUES:
            return True

        if value_norm in FALSE_VALUES:
            return False

        return np.nan

    return series.map(convert)


def find_recovery_column(df: pd.DataFrame) -> Optional[str]:

    exact = [
        "Recovered",
        "Recovery",
        "Target_Recovered",
        "Offtarget_Recovered",
        "Off_Target_Recovered",
        "Neighbor_Recovered",
        "Recovery_Status",
        "Hit",
        "Target_Hit",
    ]

    col = find_column(df, exact=exact)

    if col is not None:
        return col

    for c in df.columns:

        n = norm(c)

        if "recover" in n or "hit" in n:

            # Avoid columns such as "recovery_rank".
            if "rank" not in n and "count" not in n:
                return c

    return None


def derive_recovery_boolean(df: pd.DataFrame) -> Optional[pd.Series]:

    recovery_col = find_recovery_column(df)

    if recovery_col is not None:

        boolean = to_boolean(df[recovery_col])

        if boolean.notna().sum() > 0:
            return boolean

    # Some validation files may encode recovery using rank.
    rank_col = find_column(
        df,
        exact=[
            "Target_Rank",
            "Recovered_Target_Rank",
            "Hit_Rank",
            "Rank",
        ],
    )

    if rank_col is not None:

        rank = clean_numeric(df[rank_col])

        return rank.notna()

    return None


