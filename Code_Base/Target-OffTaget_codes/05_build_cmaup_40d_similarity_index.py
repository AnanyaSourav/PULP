def parse_feature_columns(df: pd.DataFrame) -> list[str]:
    missing = [f for f in EXPECTED_FEATURE_ORDER if f not in df.columns]
    if missing:
        raise RuntimeError(
            "The Script-04 reference is missing expected 40D features:\n"
            + "\n".join(missing)
        )
    return EXPECTED_FEATURE_ORDER.copy()


def load_manifest_features(path: Path) -> list[str]:
    df = pd.read_csv(path, sep="\t", dtype=str)

    # The Script-04 validated manifest is expected to contain Feature_Name.
    possible = [
        c for c in df.columns
        if c.lower() in {
            "feature_name",
            "feature",
            "feature_name_40d",
            "name",
        }
    ]

    if not possible:
        raise RuntimeError(
            f"Cannot identify feature-name column in manifest: {path}\n"
            f"Columns: {list(df.columns)}"
        )

    feature_col = possible[0]
    features = [str(x).strip() for x in df[feature_col].tolist() if str(x).strip()]

    if len(features) != EXPECTED_FEATURE_COUNT:
        raise RuntimeError(
            f"Validated manifest contains {len(features)} features; "
            f"expected {EXPECTED_FEATURE_COUNT}."
        )

    if features != EXPECTED_FEATURE_ORDER:
        raise RuntimeError(
            "Validated Script-04 feature order differs from the locked "
            "40-feature order.\n"
            f"Expected: {EXPECTED_FEATURE_ORDER}\n"
            f"Observed: {features}"
        )

    return features


def validate_split_file(path: Path, expected_rows: int, split_name: str) -> pd.DataFrame:
    df = pd.read_csv(path, sep="\t", dtype=str)

    if "np_id" not in df.columns:
        raise RuntimeError(f"{split_name}: missing np_id column: {path}")

    if len(df) != expected_rows:
        raise RuntimeError(
            f"{split_name}: expected {expected_rows} rows, observed {len(df)}."
        )

    ids = df["np_id"].astype(str).str.strip()

    if ids.isna().any() or (ids == "").any():
        raise RuntimeError(f"{split_name}: missing/blank np_id detected.")

    if ids.duplicated().any():
        raise RuntimeError(f"{split_name}: duplicate np_id detected.")

    return df


def make_morgan_fp(smiles: str):
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return None
    return AllChem.GetMorganFingerprintAsBitVect(
        mol,
        radius=MORGAN_RADIUS,
        nBits=MORGAN_NBITS,
    )


def bitvect_to_packed(fp) -> np.ndarray:
    # RDKit bit ordering is preserved by DataStructs.BitVectToBinaryText.
    raw = DataStructs.BitVectToBinaryText(fp)
    return np.frombuffer(raw, dtype=np.uint8).copy()


def packed_to_bit_count(packed: np.ndarray) -> np.ndarray:
    return np.unpackbits(packed, axis=1).sum(axis=1).astype(np.int16)


def cosine_similarity_self_check(x: np.ndarray) -> tuple[float, float, float]:
    # x is expected to be row-normalized.
    norms = np.linalg.norm(x, axis=1)
    return float(norms.min()), float(norms.max()), float(np.mean(norms))


