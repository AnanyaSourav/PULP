valid_count = 0
invalid_count = 0

for start in range(0, len(smiles_values), MORGAN_CHUNK_SIZE):
    stop = min(start + MORGAN_CHUNK_SIZE, len(smiles_values))

    for idx in range(start, stop):
        smi = smiles_values[idx]

        fp = make_morgan_fp(smi)

        if fp is None:
            invalid_count += 1
            morgan_qc_rows.append(
                {
                    "np_id": str(reference.iloc[idx]["np_id"]),
                    "smiles_valid_for_morgan": False,
                    "fingerprint_generated": False,
                    "bit_count": np.nan,
                    "status": "FAIL",
                }
            )
            packed_rows.append(
                np.zeros(MORGAN_NBITS // 8, dtype=np.uint8)
            )
            continue

        packed = bitvect_to_packed(fp)
        packed_rows.append(packed)
        valid_count += 1

        morgan_qc_rows.append(
            {
                "np_id": str(reference.iloc[idx]["np_id"]),
                "smiles_valid_for_morgan": True,
                "fingerprint_generated": True,
                "bit_count": int(fp.GetNumOnBits()),
                "status": "PASS",
            }
        )

    print(
        f"Morgan progress: {stop:,}/{len(smiles_values):,}",
        flush=True,
    )

